#!/usr/bin/env bash
# obsidian-update.sh -- install or update the Obsidian AppImage.
#
# Obsidian is not in the Fedora repos and installing an rpm needs root, so it
# lives as an AppImage under ~/.local/bin, owned by the user, updated by this
# script. Running it again is the update: it asks GitHub for the latest release,
# and does nothing if that is already what is installed.
#
# topgrade calls this too -- see the [commands] section of ~/.config/topgrade.toml
# -- so "update everything" keeps Obsidian current along with the rest.
#
# Usage: obsidian-update.sh [--force]

set -euo pipefail

REPO=obsidianmd/obsidian-releases
DEST_DIR="${OBSIDIAN_DIR:-$HOME/.local/bin}"
APPIMAGE="$DEST_DIR/Obsidian.AppImage"
STAMP="$DEST_DIR/.obsidian.version"
# Where the AppImage is unpacked to. See the note next to the extract step.
OPT_DIR="${OBSIDIAN_OPT:-$HOME/.local/opt/obsidian}"
FORCE=0
[ "${1:-}" = "--force" ] && FORCE=1

for c in curl jq; do
  command -v "$c" >/dev/null || { echo "obsidian-update: needs $c" >&2; exit 1; }
done

echo "obsidian-update: asking GitHub for the latest desktop release…"
# NOT /releases/latest. Obsidian publishes desktop and Android builds as
# separate releases in the same repo, and /releases/latest returned an
# Android-only release (v1.13.8, one .apk asset) on 2026-08-22. So walk the
# recent releases and take the first one that actually ships an x86_64
# AppImage — that is the desktop build. The plain AppImage is the one with no
# -arm64 or .asar.gz suffix.
releases=$(curl -fsSL "https://api.github.com/repos/$REPO/releases?per_page=30") || {
  echo "obsidian-update: could not reach the GitHub API; leaving the current build alone" >&2
  exit 1
}

read -r tag url < <(jq -r '
  [ .[]
    | select(.prerelease | not)
    | . as $r
    | .assets[]
    | select(.name | test("^Obsidian-[0-9.]+\\.AppImage$"))
    | "\($r.tag_name) \(.browser_download_url)"
  ] | first // ""' <<<"$releases")

[ -n "${tag:-}" ] && [ -n "${url:-}" ] || { echo "obsidian-update: no x86_64 AppImage in the last 30 releases" >&2; exit 1; }

current=$(cat "$STAMP" 2>/dev/null || echo none)
if [ "$FORCE" = 0 ] && [ "$current" = "$tag" ] && [ -x "$APPIMAGE" ]; then
  echo "obsidian-update: already on $tag"
  exit 0
fi

echo "obsidian-update: $current -> $tag"
mkdir -p "$DEST_DIR"
tmp=$(mktemp "$DEST_DIR/.obsidian.XXXXXX")
trap 'rm -f "$tmp"' EXIT
curl -fL --progress-bar -o "$tmp" "$url"
chmod u+x "$tmp"
# Replace in one step so a half-downloaded file can never be the thing that
# runs at login.
mv -f "$tmp" "$APPIMAGE"
trap - EXIT

# UNPACK IT, rather than running the AppImage directly.
#
# An AppImage mounts itself with FUSE. On this box `fuse` and `fuse3` are
# installed and /dev/fuse exists, but `fuse-libs` (libfuse.so.2) is NOT, so the
# AppImage exits with "AppImages require FUSE to run". Installing that package
# needs root, and this project never runs sudo — so unpack once at update time
# and run the extracted tree instead. Same binary, same release, no root, and
# it keeps working whether or not FUSE is ever fixed.
#
# If you would rather run the AppImage directly:  sudo dnf install fuse-libs
echo "obsidian-update: unpacking…"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
( cd "$work" && "$APPIMAGE" --appimage-extract >/dev/null )
[ -x "$work/squashfs-root/AppRun" ] || { echo "obsidian-update: extraction produced no AppRun" >&2; exit 1; }

mkdir -p "$(dirname "$OPT_DIR")"
rm -rf "$OPT_DIR.old"
[ -d "$OPT_DIR" ] && mv "$OPT_DIR" "$OPT_DIR.old"
mv "$work/squashfs-root" "$OPT_DIR"
rm -rf "$OPT_DIR.old"

# A wrapper on $PATH, so `obsidian` works in a terminal and from i3.
mkdir -p "$DEST_DIR"
cat > "$DEST_DIR/obsidian" <<WRAPPER
#!/usr/bin/env bash
# Generated by ~/i3-setup/scripts/obsidian-update.sh — edit that, not this.
exec "$OPT_DIR/AppRun" "\$@"
WRAPPER
chmod +x "$DEST_DIR/obsidian"

printf '%s' "$tag" > "$STAMP"
echo "obsidian-update: installed $tag -> $OPT_DIR (run it with: obsidian)"
