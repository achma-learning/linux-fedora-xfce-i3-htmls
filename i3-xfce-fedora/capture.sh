#!/usr/bin/env bash
# capture.sh -- copy the CURRENT machine's setup into this repo.
#
# This is the other half of install.sh. install.sh pushes the repo onto a fresh
# machine; capture.sh pulls a working machine back into the repo, so the two
# never drift. Run it after changing anything by hand, then commit.
#
# It reads only the files this setup owns, and writes only inside this repo.

set -euo pipefail
REPO_ROOT=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
. "$REPO_ROOT/core/common.sh"

# Every path below is relative to the repo, so be there. Without this the
# script only worked when invoked from inside its own directory.
cd "$REPO_ROOT"

LIVE_SETUP=${LIVE_SETUP:-$HOME/i3-setup}

msg "capturing from $LIVE_SETUP and ~/.config"

# --- i3 -----------------------------------------------------------------------
# The one line that differs between machines is the location of this repo, so
# it is stored as a placeholder and install.sh fills it back in.
sed 's|^set \$repo .*|set $repo __REPO__|' "$HOME/.config/i3/config" > config/i3/config
ok "i3 config ($(grep -c . config/i3/config) lines)"

# --- picom, rofi, gtk ---------------------------------------------------------
# picom.conf, rofi/, scripts/ and ai-hub/ sit at the repo ROOT, not under
# config/, because the i3 config reads them from there at run time
# ($repo/picom.conf, $repo/rofi/...). Keeping the repo layout identical to the
# runtime layout means nothing has to be copied or published at install time,
# and there is only ever one copy of each file.
cp -f "$LIVE_SETUP/picom.conf" picom.conf
ok "picom.conf"

mkdir -p rofi && cp -f "$LIVE_SETUP"/rofi/*.rasi rofi/
ok "rofi theme(s): $(ls rofi | tr '\n' ' ')"

# The whole gtk-3.0 directory, minus runtime junk: gtk.css @imports colors.css,
# which in turn needs the assets, so shipping gtk.css alone would not reproduce
# the look.
mkdir -p config/gtk-3.0
rsync -a --delete \
  --exclude 'settings.ini.lock' --exclude '*.bak.*' \
  "$HOME/.config/gtk-3.0/" config/gtk-3.0/ 2>/dev/null \
  || cp -a "$HOME/.config/gtk-3.0/." config/gtk-3.0/
ok "gtk-3.0 ($(find config/gtk-3.0 -type f | wc -l) files)"

# --- xfce4 panels -------------------------------------------------------------
# xfce4-panel-profiles serialises BOTH panels with every plugin, launcher and
# setting into one archive. Rebuilding that from individual xfconf-query calls
# was tried and is not worth it — launchers alone are dozens of generated
# .desktop files.
if command_exists xfce4-panel-profiles; then
  rm -f config/xfce4/panel-profile.tar.bz2
  xfce4-panel-profiles save config/xfce4/panel-profile.tar.bz2 >/dev/null
  ok "panel profile ($(du -h config/xfce4/panel-profile.tar.bz2 | cut -f1))"
else
  warn "xfce4-panel-profiles not installed — panel layout NOT captured"
fi

# xsettings carries the GTK theme, icon theme, fonts and DPI. Saved as a
# replayable script rather than a dump format, so it is readable in a diff.
{
  echo "# generated by capture.sh -- replayed by core/50-panels.sh"
  xfconf-query -c xsettings -l -v | while read -r prop value; do
    [ -n "$value" ] || continue
    printf 'xfconf-query -c xsettings -p %s -s %q\n' "$prop" "$value"
  done
} > config/xfce4/xsettings.sh
ok "xsettings ($(grep -c xfconf-query config/xfce4/xsettings.sh) properties)"

# --- runtime scripts and the AI hub -------------------------------------------
rm -rf scripts && mkdir -p scripts
cp -a "$LIVE_SETUP"/scripts/*.sh "$LIVE_SETUP"/scripts/*.py scripts/ 2>/dev/null || true
cp -a "$LIVE_SETUP"/scripts/*.sh scripts/ 2>/dev/null || true
chmod +x scripts/* 2>/dev/null || true
ok "scripts: $(ls scripts | tr '\n' ' ')"

rm -rf ai-hub && cp -a "$LIVE_SETUP/ai-hub" ai-hub
rm -rf ai-hub/bin/__pycache__
ok "ai-hub"

# --- what is installed --------------------------------------------------------
# Not used by install.sh (its package list is deliberately hand-picked), but
# invaluable when something turns out to be missing on a fresh machine.
rpm -qa --qf '%{NAME}\n' | sort > config/installed-packages.txt
ok "package inventory ($(wc -l < config/installed-packages.txt) packages)"

msg "done. Review with: git -C \"$REPO_ROOT\" status"
